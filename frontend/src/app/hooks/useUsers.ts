import { toast } from 'sonner';
import { useTranslation } from 'react-i18next';
import { api, getErrorMessage } from '../services/api';
import { useApiResource } from './useApiResource';
import type { AppUser, CreateUserPayload, UpdateUserPayload } from '../types';

const asUserList = (raw: unknown): AppUser[] => (Array.isArray(raw) ? (raw as AppUser[]) : []);

/**
 * Admin user management: the list plus its four mutations.
 *
 * Every mutation reports success/failure through a toast and refreshes the list
 * on success; the hook never swallows an error silently, so the page does not
 * have to duplicate try/catch blocks.
 */
export const useUsers = () => {
  const { t } = useTranslation();
  const {
    data: users,
    loading: isLoading,
    error,
    reload: fetchUsers,
  } = useApiResource<AppUser[]>(
    '/users',
    [],
    t('admin.userManagement.errors.fetch', 'Gagal memuat data pengguna.'),
    asUserList,
  );

  const addUser = async (payload: CreateUserPayload) => {
    try {
      await api.post('/users', payload);
      toast.success(
        t(
          'admin.userManagement.success.add',
          'User berhasil dibuat. Kredensial telah dikirim ke email mereka.',
        ),
      );
      await fetchUsers();
      return { success: true as const };
    } catch (err) {
      toast.error(getErrorMessage(err, t('admin.userManagement.errors.add', 'Gagal membuat pengguna.')));
      return { success: false as const };
    }
  };

  // Backend only accepts the role field; name and email stay immutable.
  const updateUser = async (id: string, payload: UpdateUserPayload) => {
    try {
      await api.patch(`/users/${id}`, payload);
      toast.success(
        t('admin.userManagement.success.update', 'Hak akses pengguna berhasil diperbarui!'),
      );
      await fetchUsers();
      return { success: true as const };
    } catch (err) {
      toast.error(getErrorMessage(err, t('admin.userManagement.errors.update', 'Gagal memperbarui pengguna.')));
      return { success: false as const };
    }
  };

  const deleteUser = async (id: string) => {
    try {
      await api.delete(`/users/${id}`);
      toast.success(t('admin.userManagement.success.delete', 'Pengguna berhasil dihapus permanen!'));
      await fetchUsers();
      return { success: true as const };
    } catch (err) {
      toast.error(getErrorMessage(err, t('admin.userManagement.errors.delete', 'Gagal menghapus pengguna.')));
      return { success: false as const };
    }
  };

  // Random password is generated by the backend and emailed to the user.
  const resetPassword = async (id: string) => {
    try {
      await api.patch(`/auth/${id}/admin-reset-password`);
      toast.success(t('admin.userManagement.success.reset', 'Password baru telah dikirim ke email.'));
      return { success: true as const };
    } catch (err) {
      toast.error(getErrorMessage(err, t('admin.userManagement.errors.reset', 'Gagal mereset password.')));
      return { success: false as const };
    }
  };

  return { users, isLoading, error, fetchUsers, addUser, updateUser, deleteUser, resetPassword };
};
